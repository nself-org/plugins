#!/usr/bin/env bash
# genkeys.sh [--keys-dir DIR] OUTPUT.go
#
# Purpose: generate free/ci/internal/agent/verify/keys_gen.go from the committed agent public keys, because go:embed cannot reach
#   outside the module (hq NODE D11, review F11). `go generate ./internal/agent/verify/...` calls it; a drift test regenerates into a
#   temp file and compares, so the compiled-in key set is always exactly scripts/release/keys/agent-*.pub.
#
# Inputs:  scripts/release/keys/agent-<16 hex>.pub   PEM SPKI Ed25519 public keys, one per file; the 16 hex must be the first 16 hex of
#          sha256(raw 32-byte public key), so the key id (agent-<16 hex>) is derived and a mis-named file fails here.
#          agent-revoked.txt (optional, same directory): one revoked key id per line, "agent-<16 hex>"; blank lines and lines starting with # are
#          ignored. A leaked key stays in the set of files but is refused at verify time.
#          --keys-dir DIR   read DIR instead (tests).   OPENSSL   optional OpenSSL 3 binary.
# Output:  OUTPUT.go, byte-stable (sorted by id). With no key files the set is empty; P7-NODE-29 commits the first agent key.
# Exit 0 ok, 1 failure, 2 usage. Public keys only: there is no private key here and never will be.

set -euo pipefail

err() { printf "[agent-genkeys] ERROR: %s\n" "$*" >&2; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KEYS_DIR="${SCRIPT_DIR}/../keys"
if [ "${1:-}" = "--keys-dir" ]; then
  [ "$#" -ge 2 ] || { printf "usage: %s [--keys-dir DIR] OUTPUT.go\n" "$0" >&2; exit 2; }
  KEYS_DIR="$2"
  shift 2
fi
if [ "$#" -ne 1 ] || [ -z "$1" ]; then
  printf "usage: %s [--keys-dir DIR] OUTPUT.go\n" "$0" >&2
  exit 2
fi
OUTPUT="$1"
[ -d "$KEYS_DIR" ] || { err "keys directory not found: $KEYS_DIR"; exit 1; }

O="${OPENSSL:-openssl}"
command -v "$O" >/dev/null 2>&1 || { err "openssl not found (set OPENSSL to an OpenSSL 3 binary)"; exit 1; }
"$O" version 2>/dev/null | grep -q '^OpenSSL ' || { err "$O is not OpenSSL; set OPENSSL"; exit 1; }

rows=""
for f in "$KEYS_DIR"/agent-*.pub; do
  [ -f "$f" ] || continue
  base="$(basename "$f" .pub)"
  [[ "$base" =~ ^agent-[0-9a-f]{16}$ ]] || { err "$(basename "$f") must be named agent-<16 hex>.pub"; exit 1; }
  raw="$(mktemp "${TMPDIR:-/tmp}/agent-genkeys.XXXXXX")"
  "$O" pkey -pubin -in "$f" -outform DER 2>/dev/null | tail -c 32 > "$raw" || { rm -f "$raw"; err "$(basename "$f") is not a readable public key"; exit 1; }
  [ "$(wc -c < "$raw" | tr -d ' ')" = "32" ] || { rm -f "$raw"; err "$(basename "$f") is not a 32-byte Ed25519 public key"; exit 1; }
  # An Ed25519 SPKI is a fixed 12-byte header plus the key; anything else (RSA, EC) is refused above by length or here by the type.
  "$O" pkey -pubin -in "$f" -noout -text 2>/dev/null | grep -q '^ED25519 Public-Key:' || { rm -f "$raw"; err "$(basename "$f") is not an Ed25519 key"; exit 1; }
  derived="agent-$({ sha256sum "$raw" 2>/dev/null || shasum -a 256 "$raw"; } | cut -c1-16)"
  b64="$("$O" base64 -A -in "$raw")"
  rm -f "$raw"
  [ "$derived" = "$base" ] || { err "$(basename "$f") does not match its key (expected agent-<16 hex of sha256(public key)> = $derived)"; exit 1; }
  rows+="$(printf '\t{ID: "%s", Public: "%s"},' "$base" "$b64")"$'\n'
done

revoked=""
if [ -f "$KEYS_DIR/agent-revoked.txt" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    case "$line" in ''|'#'*) continue ;; esac
    [[ "$line" =~ ^agent-[0-9a-f]{16}$ ]] || { err "agent-revoked.txt: '$line' is not a derived key id (agent-<16 hex>)"; exit 1; }
    revoked+="$(printf '\t"%s",' "$line")"$'\n'
  done < "$KEYS_DIR/agent-revoked.txt"
fi

{
  printf '// GENERATED BY scripts/release/agent/genkeys.sh (go generate ./internal/agent/verify/...) DO NOT HAND EDIT.\n'
  printf '// Source: scripts/release/keys/agent-*.pub. Empty until P7-NODE-29 commits the first agent public key.\n\n'
  printf 'package verify\n\n'
  printf '// keyEntry is one compiled-in agent public key: its derived id and the raw 32-byte key in standard base64.\n'
  printf 'type keyEntry struct{ ID, Public string }\n\n'
  printf '// generatedKeys is the trusted agent key set.\n'
  if [ -z "$rows" ]; then
    printf 'var generatedKeys = []keyEntry{}\n'
  else
    printf 'var generatedKeys = []keyEntry{\n%s}\n' "$(printf '%s' "$rows" | LC_ALL=C sort)"
  fi
  printf '\n// generatedRevoked is the revoked key id list (scripts/release/keys/agent-revoked.txt).\n'
  if [ -z "$revoked" ]; then
    printf 'var generatedRevoked = []string{}\n'
  else
    printf 'var generatedRevoked = []string{\n%s}\n' "$(printf '%s' "$revoked" | LC_ALL=C sort -u)"
  fi
} > "$OUTPUT"
