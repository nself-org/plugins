#!/usr/bin/env bash
# Shared by the acceptance scenario drills (P7-CI-47); sourced, never run.
#
# Purpose: write the fixture repositories the scenarios run `nself ci` in. They are generated rather than committed so
#   that no go.mod, package.json or Cargo.toml lives under this repository's own tree (the repo's detectors and
#   dependabot would pick them up).
# Inputs:  a target directory (created, must be empty).
# Outputs: a committed git repository with no remote. fx_go: Go, stdlib only. fx_node: Node + pnpm-lock, no dependencies.
#          fx_rust: Cargo, no dependencies. fx_polyglot: Go + Dockerfile + a declared postgres service job.
# Constraints: obviously fake content only; formatted so go.fmt passes; no network needed to build or test.

fx_commit() { # fx_commit DIR MESSAGE
	git -C "$1" init -q -b main
	git -C "$1" add -A
	git -C "$1" -c user.email=drill@example.test -c user.name=drill -c commit.gpgsign=false commit -q -m "$2"
}

fx_go_files() {
	mkdir -p "$1"
	cat >"$1/go.mod" <<'GO'
module example.test/hello

go 1.22
GO
	cat >"$1/main.go" <<'GO'
package main

import "fmt"

func main() { fmt.Println(Greet("world")) }

// Greet returns the greeting for name.
func Greet(name string) string { return "hello, " + name }
GO
	cat >"$1/main_test.go" <<'GO'
package main

import "testing"

func TestGreet(t *testing.T) {
	if got := Greet("drill"); got != "hello, drill" {
		t.Fatalf("Greet = %q", got)
	}
}
GO
}

fx_go() { fx_go_files "$1"; fx_commit "$1" "go fixture"; }

# fx_lockfile DIR: the go.sum a lockfile change commits (a fake, well-formed entry).
fx_lockfile() { printf 'example.test/dep v1.0.0 h1:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=\n' >"$1/go.sum"; }

fx_node() {
	mkdir -p "$1"
	cat >"$1/package.json" <<'JSON'
{
  "name": "drill-node-fixture",
  "version": "0.0.0",
  "private": true,
  "scripts": { "test": "node --test" },
  "packageManager": "pnpm@9.0.0"
}
JSON
	printf "lockfileVersion: '9.0'\n\nsettings:\n  autoInstallPeers: true\n  excludeLinksFromLockfile: false\n\nimporters:\n\n  .: {}\n" >"$1/pnpm-lock.yaml"
	printf 'const test = require("node:test");\nconst assert = require("node:assert");\n\ntest("adds", () => assert.strictEqual(1 + 1, 2));\n' >"$1/index.test.js"
	fx_commit "$1" "node fixture"
}

fx_rust() {
	mkdir -p "$1/src"
	printf '[package]\nname = "drill-rust-fixture"\nversion = "0.0.0"\nedition = "2021"\n\n[dependencies]\n' >"$1/Cargo.toml"
	printf '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "drill-rust-fixture"\nversion = "0.0.0"\n' >"$1/Cargo.lock"
	printf 'fn main() {\n    println!("{}", greet("world"));\n}\n\nfn greet(name: &str) -> String {\n    format!("hello, {name}")\n}\n\n#[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    fn greets() {\n        assert_eq!(greet("a"), "hello, a");\n    }\n}\n' >"$1/src/main.rs"
	fx_commit "$1" "rust fixture"
}

# fx_polyglot DIR: Go + a web package + Dockerfile, with authored jobs (an authored job list replaces detection; a Linux job
# runs under an address-space limit of its requested memory, so the Go jobs ask for enough) and one job that
# needs the declared postgres service (it only proves the connection variables are injected and the port accepts a TCP
# connection).
fx_polyglot() {
	fx_go_files "$1"
	mkdir -p "$1/.nself" "$1/web"
	printf 'FROM scratch\nCOPY main.go /main.go\n' >"$1/Dockerfile"
	printf '{\n  "name": "drill-web",\n  "version": "0.0.0",\n  "private": true\n}\n' >"$1/web/package.json"
	cat >"$1/.nself/ci.yaml" <<'YAML'
version: 1
services:
  db:
    component: postgres
jobs:
  go-fmt:
    kind: static
    run: [bash, -c, 'test -z "$(gofmt -l .)"']
    requires: { mem_mb: 2048 }
  go-test:
    kind: test
    run: [go, test, ./...]
    timeout: 300s
    requires: { mem_mb: 4096 }
  web-check:
    kind: static
    run: [jq, -e, .name, package.json]
    workdir: web
  db-reachable:
    kind: test
    run:
      - bash
      - -c
      - 'test -n "$NSELF_CI_SERVICE_DB_URL" && exec 3<>"/dev/tcp/$NSELF_CI_SERVICE_DB_HOST/$NSELF_CI_SERVICE_DB_PORT"'
    needs_services: [db]
    timeout: 240s
YAML
	fx_commit "$1" "polyglot fixture"
}
