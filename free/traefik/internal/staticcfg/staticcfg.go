// Package staticcfg renders Traefik's static configuration from the embedded base file.
//
// Traefik's static file cannot interpolate environment variables, so the optional "upload"
// entrypoint (a separate listener with its own readTimeout, carrying only named routes) is added
// here from the renderer flags. The base keeps its comments; web and websecure are never touched.
package staticcfg

import (
	"bytes"
	"fmt"
	"time"

	"gopkg.in/yaml.v3"
)

// Header marks the output as generated.
const Header = "# GENERATED BY nself traefik renderer - DO NOT HAND EDIT\n"

// Address is the container port of the upload entrypoint.
const Address = ":8444"

// Bounds of the upload readTimeout: not below the 60s of web/websecure (it would not be a knob
// then) and not above a day.
const (
	MinReadTimeout = 60 * time.Second
	MaxReadTimeout = 24 * time.Hour
)

// Upload configures the optional upload entrypoint.
type Upload struct {
	Enabled     bool
	ReadTimeout time.Duration
}

// Validate refuses an enabled upload entrypoint whose readTimeout is outside 60s..24h or not a
// whole number of seconds. A disabled one is always valid (its timeout is unused).
func (u Upload) Validate() error {
	if !u.Enabled {
		return nil
	}
	if u.ReadTimeout < MinReadTimeout || u.ReadTimeout > MaxReadTimeout || u.ReadTimeout%time.Second != 0 {
		return fmt.Errorf("--upload-read-timeout %s must be a whole number of seconds between %s and %s", u.ReadTimeout, MinReadTimeout, MaxReadTimeout)
	}
	return nil
}

// Render returns the static configuration: the generated header, then base unchanged when the
// upload entrypoint is disabled, or base plus entryPoints.upload when it is enabled.
func Render(base []byte, up Upload) ([]byte, error) {
	if err := up.Validate(); err != nil {
		return nil, err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(base, &doc); err != nil {
		return nil, fmt.Errorf("static base: %w", err)
	}
	if !up.Enabled {
		return append([]byte(Header), base...), nil
	}
	eps := child(root(&doc), "entryPoints")
	if eps == nil || eps.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("static base has no entryPoints mapping")
	}
	if child(eps, "upload") != nil {
		return nil, fmt.Errorf("static base already defines entryPoints.upload")
	}
	var node yaml.Node
	spec := fmt.Sprintf(`address: %q
http:
  encodedCharacters:
    allowEncodedSlash: false
transport:
  respondingTimeouts:
    readTimeout: %ds
    writeTimeout: 0s
    idleTimeout: 65s
`, Address, int64(up.ReadTimeout/time.Second))
	if err := yaml.Unmarshal([]byte(spec), &node); err != nil {
		return nil, err
	}
	key := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "upload",
		HeadComment: "Upload entrypoint: carries only the routes named in TRAEFIK_UPLOAD_ROUTES, with its own readTimeout."}
	eps.Content = append(eps.Content, key, node.Content[0])
	var buf bytes.Buffer
	buf.WriteString(Header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// root is the top mapping of a parsed document.
func root(doc *yaml.Node) *yaml.Node {
	if doc.Kind == yaml.DocumentNode && len(doc.Content) > 0 {
		return doc.Content[0]
	}
	return doc
}

// child returns the value node of key in mapping m, or nil.
func child(m *yaml.Node, key string) *yaml.Node {
	if m == nil || m.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}
