// Command render is the traefik plugin's single binary.
//
//	render --routes routes.json --out DIR [--ssl DIR] [--cert-root DIR] [--helper URL]
//	       [--static-out DIR] [--upload-routes ID,ID] [--upload-read-timeout 600s]
//	render serve-static --root DIR --listen :8080
//	render healthcheck --addr 127.0.0.1:8080
//
// render reads contract:cli.proxy-routes v1 and writes DIR/dynamic.yml (atomic:
// temp file plus rename) and DIR/.nself-generated. With --static-out it also writes
// DIR/traefik.yml (the embedded static configuration, plus the "upload" entrypoint when
// --upload-routes names routes; --upload-read-timeout is its readTimeout, 60s to 24h) and
// DIR/.nself-generated. Both documents are validated and rendered before the first write, so a
// refusal writes nothing. Exit 0 ok, 1 refusal or invalid input (nothing is written), 2 I/O error
// or a malformed flag.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"time"

	"github.com/nself-org/plugins/free/traefik/config"
	"github.com/nself-org/plugins/free/traefik/internal/contract"
	"github.com/nself-org/plugins/free/traefik/internal/render"
	"github.com/nself-org/plugins/free/traefik/internal/static"
	"github.com/nself-org/plugins/free/traefik/internal/staticcfg"
)

const marker = "GENERATED BY nself traefik renderer - DO NOT HAND EDIT\n"

func main() { os.Exit(run(os.Args[1:], os.Stderr)) }

func run(args []string, errw io.Writer) int {
	if len(args) > 0 && args[0] == "serve-static" {
		return serve(args[1:], errw)
	}
	if len(args) > 0 && args[0] == "healthcheck" {
		return health(args[1:], errw)
	}
	fs := flag.NewFlagSet("render", flag.ContinueOnError)
	fs.SetOutput(errw)
	routes := fs.String("routes", "/nself/routes.json", "routes.json (contract:cli.proxy-routes v1)")
	out := fs.String("out", "/dynamic", "directory that receives dynamic.yml")
	ssl := fs.String("ssl", "/nself/ssl", "ssl/ directory (certificates/<dir>)")
	certRoot := fs.String("cert-root", "", "ssl/ as Traefik sees it (default --ssl)")
	helper := fs.String("helper", "http://traefik-acme:8080", "traefik-acme base URL")
	staticOut := fs.String("static-out", "", "directory that receives traefik.yml (static configuration); empty writes none")
	uploadRoutes := fs.String("upload-routes", "", "comma-separated route ids also served on the upload entrypoint (:8444)")
	uploadTimeout := fs.Duration("upload-read-timeout", 600*time.Second, "readTimeout of the upload entrypoint (60s to 24h)")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	ids := splitIDs(*uploadRoutes)
	up := staticcfg.Upload{Enabled: len(ids) > 0, ReadTimeout: *uploadTimeout}
	if err := up.Validate(); err != nil {
		_, _ = fmt.Fprintln(errw, "render:", err)
		return 1
	}
	if up.Enabled && *staticOut == "" {
		_, _ = fmt.Fprintln(errw, "render: --upload-routes needs --static-out (the upload entrypoint lives in the static configuration)")
		return 1
	}
	f, err := os.Open(*routes)
	if err != nil {
		_, _ = fmt.Fprintln(errw, "render:", err)
		return 2
	}
	defer func() { _ = f.Close() }()
	m, err := contract.Load(f)
	if err != nil {
		_, _ = fmt.Fprintln(errw, "render:", err)
		return 1
	}
	data, err := render.Render(m, render.Options{SSLRoot: *ssl, CertRoot: *certRoot, Helper: *helper, Upload: ids})
	var ref *render.RefusalError
	if errors.As(err, &ref) {
		_, _ = fmt.Fprintln(errw, ref.Error())
		return 1
	}
	if err != nil {
		_, _ = fmt.Fprintln(errw, "render:", err)
		return 2
	}
	var staticDoc []byte
	if *staticOut != "" {
		if staticDoc, err = staticcfg.Render(config.Base, up); err != nil {
			_, _ = fmt.Fprintln(errw, "render:", err)
			return 1
		}
		if err := writeDoc(*staticOut, "traefik.yml", staticDoc); err != nil {
			_, _ = fmt.Fprintln(errw, "render:", err)
			return 2
		}
	}
	if err := writeDoc(*out, "dynamic.yml", data); err != nil {
		_, _ = fmt.Fprintln(errw, "render:", err)
		return 2
	}
	return 0
}

func serve(args []string, errw io.Writer) int {
	fs := flag.NewFlagSet("serve-static", flag.ContinueOnError)
	fs.SetOutput(errw)
	root := fs.String("root", "/acme-webroot", "ACME webroot (read-only)")
	listen := fs.String("listen", ":8080", "listen address")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	srv := &http.Server{Addr: *listen, Handler: static.Handler(*root), ReadHeaderTimeout: 10 * time.Second}
	_, _ = fmt.Fprintln(errw, "serve-static:", srv.ListenAndServe())
	return 2
}

// health is the traefik-acme container health check: GET /__nself/ok must answer 200.
func health(args []string, errw io.Writer) int {
	fs := flag.NewFlagSet("healthcheck", flag.ContinueOnError)
	fs.SetOutput(errw)
	addr := fs.String("addr", "127.0.0.1:8080", "serve-static address")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	c := http.Client{Timeout: 2 * time.Second}
	resp, err := c.Get("http://" + *addr + "/__nself/ok")
	if err != nil {
		_, _ = fmt.Fprintln(errw, "healthcheck:", err)
		return 1
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		_, _ = fmt.Fprintln(errw, "healthcheck: status", resp.StatusCode)
		return 1
	}
	return 0
}
