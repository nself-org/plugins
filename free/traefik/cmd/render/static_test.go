package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// runStatic renders http-full with extra flags into fresh dirs and returns the exit code,
// stderr and the two output directories.
func runStatic(t *testing.T, extra ...string) (int, string, string, string) {
	t.Helper()
	out, st := t.TempDir(), t.TempDir()
	var errb bytes.Buffer
	args := append([]string{"--routes", fx("http-full"), "--out", out, "--ssl", t.TempDir(), "--static-out", st}, extra...)
	return run(args, &errb), errb.String(), out, st
}

func empty(t *testing.T, dirs ...string) {
	t.Helper()
	for _, d := range dirs {
		if ents, _ := os.ReadDir(d); len(ents) != 0 {
			t.Errorf("%s: a refusal wrote files: %v", d, ents)
		}
	}
}

func TestStaticOutWithoutUploadWritesTheBase(t *testing.T) {
	rc, msg, out, st := runStatic(t)
	if rc != 0 {
		t.Fatalf("exit %d: %s", rc, msg)
	}
	b, err := os.ReadFile(filepath.Join(st, "traefik.yml"))
	if err != nil || !strings.HasPrefix(string(b), "# GENERATED BY nself traefik renderer") || strings.Contains(string(b), "upload:") {
		t.Fatalf("static file: %v %q", err, b)
	}
	for _, d := range []string{out, st} {
		if _, err := os.Stat(filepath.Join(d, ".nself-generated")); err != nil {
			t.Errorf("%s: no marker", d)
		}
	}
}

func TestUploadRoutesWriteTheUploadEntrypointAndRouters(t *testing.T) {
	rc, msg, out, st := runStatic(t, "--upload-routes", "core:storage, ", "--upload-read-timeout", "120s")
	if rc != 0 {
		t.Fatalf("exit %d: %s", rc, msg)
	}
	b, _ := os.ReadFile(filepath.Join(st, "traefik.yml"))
	for _, want := range []string{"upload:", `address: ":8444"`, "readTimeout: 120s", "readTimeout: 60s"} {
		if !strings.Contains(string(b), want) {
			t.Errorf("static file lacks %q", want)
		}
	}
	d, _ := os.ReadFile(filepath.Join(out, "dynamic.yml"))
	if !strings.Contains(string(d), "- upload") {
		t.Error("dynamic.yml has no router on the upload entrypoint")
	}
}

func TestBadUploadFlagsWriteNothing(t *testing.T) {
	for _, c := range []struct {
		name string
		args []string
		rc   int
		msg  string
	}{
		{"timeout below 60s", []string{"--upload-routes", "core:storage", "--upload-read-timeout", "30s"}, 1, "--upload-read-timeout"},
		{"timeout above 24h", []string{"--upload-routes", "core:storage", "--upload-read-timeout", "25h"}, 1, "--upload-read-timeout"},
		{"unknown route", []string{"--upload-routes", "core:storage,nope:1"}, 1, "upload_routes"},
		{"malformed duration", []string{"--upload-routes", "core:storage", "--upload-read-timeout", "soon"}, 2, "upload-read-timeout"},
	} {
		rc, msg, out, st := runStatic(t, c.args...)
		if rc != c.rc || !strings.Contains(msg, c.msg) {
			t.Errorf("%s: exit %d (want %d), stderr %q", c.name, rc, c.rc, msg)
		}
		empty(t, out, st)
	}
	// upload routes without a static output directory have nowhere to put the entrypoint
	var errb bytes.Buffer
	out := t.TempDir()
	rc := run([]string{"--routes", fx("http-full"), "--out", out, "--ssl", t.TempDir(), "--upload-routes", "core:storage"}, &errb)
	if rc != 1 || !strings.Contains(errb.String(), "--static-out") {
		t.Errorf("no static-out: exit %d: %s", rc, errb.String())
	}
	empty(t, out)
	// a timeout is not checked when no route is named
	if rc, msg, _, _ := runStatic(t, "--upload-read-timeout", "1s"); rc != 0 {
		t.Errorf("unused timeout rejected: %d %s", rc, msg)
	}
}
