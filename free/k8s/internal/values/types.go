// Purpose: the output schema of `nself k8s values`: the values.yaml document
// (everything except env values) and the secrets.yaml document (every env
// value). The chart in charts/nself renders these two files and nothing else.
//
// Inputs: none (type definitions only).
//
// Outputs: Values, Secrets and their parts; Kind and pull-policy constants.
//
// Constraints: values.yaml carries env and init-script NAMES only; secrets.yaml
// carries every env VALUE and every init-script CONTENT. Field order here is
// the emitted order; maps are emitted with sorted keys, so the output is
// byte-stable.
package values

// PullIfNotPresent is the pull policy set on every mapped workload.
const PullIfNotPresent = "IfNotPresent"

// Service kinds. The chart picks the workload template by this field.
const (
	KindDeployment  = "deployment"
	KindStatefulSet = "statefulset"
	KindJob         = "job"
	// KindIngress marks the compose nginx service: it is not deployed, its
	// routes become Ingress rules (Values.Ingress).
	KindIngress = "ingress"
)

// GeneratedMarker is the first line of every generated file.
const GeneratedMarker = "# GENERATED BY nself k8s values - DO NOT HAND EDIT"

// Values is the document written to .nself/generated/k8s/values.yaml.
type Values struct {
	Project string `yaml:"project"`
	// BaseDomain is the project's BASE_DOMAIN as the resolved compose model
	// carries it; the chart rewrites ingress hosts from it to the install
	// --domain. Omitted when the model has no single reliable value.
	BaseDomain    string             `yaml:"baseDomain,omitempty"`
	Services      map[string]Service `yaml:"services"`
	Volumes       map[string]Volume  `yaml:"volumes,omitempty"`
	Ingress       Ingress            `yaml:"ingress"`
	Unsupported   []Unsupported      `yaml:"unsupported"`
	UnmappedRoute []Unsupported      `yaml:"unmappedRoutes"`
}

// Service is one compose service projected to a workload.
type Service struct {
	Kind   string `yaml:"kind"`
	Image  string `yaml:"image"`
	Tag    string `yaml:"tag,omitempty"`
	Digest string `yaml:"digest,omitempty"`
	// PullPolicy is the image pull policy of a workload (never set on the
	// Ingress kind). The chart does not read it yet; a follow-up wires it to
	// imagePullPolicy.
	PullPolicy string   `yaml:"pullPolicy,omitempty"`
	Entrypoint []string `yaml:"entrypoint,omitempty"`
	Command    []string `yaml:"command,omitempty"`
	Env        []string `yaml:"env,omitempty"`
	Ports      []Port   `yaml:"ports,omitempty"`
	Mounts     []Mount  `yaml:"mounts,omitempty"`
	Probe      *Probe   `yaml:"probe,omitempty"`
	// Plugin is the plugin name when the service is a plugin workload: the
	// service is called plugin-<name>, or the CLI gave it the compose hostname
	// plugin-<name> (most plugin fragments use a bare service name). The chart
	// checks plugins.install against it and gives these workloads the licence
	// Secret.
	Plugin string `yaml:"plugin,omitempty"`
	// InitDB names the init scripts of the /docker-entrypoint-initdb.d bind
	// mount, sorted. Their contents live in secrets.yaml (Secrets.InitDB),
	// never here: an init script may hold a password.
	InitDB    []string `yaml:"initdb,omitempty"`
	NotMapped []string `yaml:"notMapped,omitempty"`
}

// Port is a container port (compose "target"); published ports do not exist
// in a cluster.
type Port struct {
	Port     int    `yaml:"port"`
	Protocol string `yaml:"protocol"`
}

// Mount attaches a named volume (Volumes key) to a path.
type Mount struct {
	Volume   string `yaml:"volume"`
	Path     string `yaml:"path"`
	ReadOnly bool   `yaml:"readOnly,omitempty"`
}

// Volume is a named compose volume, rendered as a PersistentVolumeClaim.
type Volume struct {
	Claim string `yaml:"claim"`
}

// Probe is a compose healthcheck as an exec readiness probe.
type Probe struct {
	Exec         []string `yaml:"exec"`
	PeriodS      int      `yaml:"periodSeconds"`
	TimeoutS     int      `yaml:"timeoutSeconds"`
	Retries      int      `yaml:"failureThreshold"`
	StartPeriodS int      `yaml:"initialDelaySeconds"`
}

// Ingress holds the Ingress rules built from the nginx routes.
type Ingress struct {
	Rules []Rule `yaml:"rules"`
}

// Rule is one host routed to one in-cluster Service.
type Rule struct {
	Name    string `yaml:"name"`
	Host    string `yaml:"host"`
	Service string `yaml:"service"`
	Port    int    `yaml:"port"`
	Scheme  string `yaml:"scheme"`
}

// Unsupported names something that has no k8s mapping, with the reason.
type Unsupported struct {
	Name   string `yaml:"name"`
	Reason string `yaml:"reason"`
}

// Secrets is the document written to .nself/generated/k8s/secrets.yaml
// (mode 0600): service name -> env name -> value, and service name -> init
// script name -> content (a .sql.gz script is base64 text, the others are
// plain text).
type Secrets struct {
	Secrets map[string]map[string]string `yaml:"secrets"`
	InitDB  map[string]map[string]string `yaml:"initdb,omitempty"`
}
