package main

// Purpose: `nself ci providers gitlab init [--check] [--stdout] [--dir <repo>] [--json]` (P7-HOST-06,
// Epic D11): render the GitLab include file from templates/gitlab, write it to
// <repo>/.gitlab/nself-ci.gitlab-ci.yml (or stdout), or check that the default branch and the untrusted
// ref copies in local git still equal the rendering. It also links the GitLab dispatch provider and the
// GitLab status adapter into the binary (their init() registers them).
// Inputs:  argv after the key; the pinned agent commit of templates/gitlab; local git.
// Outputs: the file, or its text on stdout, or a per-ref report with the exact commands that create or
//          update the untrusted ref (never run here); one v1 JSON envelope with --json.
// Constraints: V15 only; side-effect class: writes one local file and nothing else, never pushes, never
//          calls the network; an existing file that is not generated (no marker) is never overwritten;
//          git runs through the CI command funnel (report.Capture); exit 0 ok, 1 drift or refusal, 2
//          usage (the shared usage helper returns 1, as for every providers subcommand).

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/nself-org/cli/sdk/go/v2/output"

	"github.com/nself-org/plugins/free/ci/internal/providers/gitlab/pipeline"
	_ "github.com/nself-org/plugins/free/ci/internal/providers/gitlab/status" // registers the GitLab commit-status reporter
	"github.com/nself-org/plugins/free/ci/internal/report"
	gitlabtmpl "github.com/nself-org/plugins/free/ci/templates/gitlab"
)

type gitlabInitFlags struct {
	check, stdout, json bool
	dir                 string
}

func newGitlabInitFlags(f *gitlabInitFlags) *flag.FlagSet {
	fs := flag.NewFlagSet("providers gitlab init", flag.ContinueOnError)
	fs.BoolVar(&f.check, "check", false, "compare the default-branch and untrusted-ref copies in local git with the rendering")
	fs.BoolVar(&f.stdout, "stdout", false, "print the include file instead of writing it")
	fs.StringVar(&f.dir, "dir", "", "repository root (env NSELF_CI_REPO; default: current directory)")
	fs.BoolVar(&f.json, "json", false, "print one v1 JSON envelope")
	return fs
}

func init() {
	registerV15("providers gitlab init", subcommandEntry{V15Only: true, Handler: runGitlabInit,
		Flags: func() *flag.FlagSet { return newGitlabInitFlags(&gitlabInitFlags{}) }})
}

func gitlabInitFail(f gitlabInitFlags, code string, err error) int {
	if f.json {
		_ = output.WriteError(os.Stdout, "ci providers gitlab init", output.ErrorDetail{Code: code, Message: err.Error(), ExitCode: 1}, nil)
	} else {
		fmt.Fprintln(os.Stderr, "error:", err)
	}
	return 1
}

// gitlabRender renders the include file for the newest pinned agent commit.
func gitlabRender() ([]byte, string, error) {
	commits, err := gitlabtmpl.SourceCommits()
	if err != nil {
		return nil, "", fmt.Errorf("no agent commit is pinned in this build")
	}
	commit := commits[len(commits)-1]
	doc, err := gitlabtmpl.Render(gitlabtmpl.Options{AgentCommit: commit})
	return doc, commit, err
}

func runGitlabInit(args []string) int {
	var f gitlabInitFlags
	fs := newGitlabInitFlags(&f)
	if err := fs.Parse(args); err != nil || fs.NArg() != 0 || f.check && f.stdout {
		return usageErr("nself ci providers gitlab init [--check | --stdout] [--dir <repo>] [--json]")
	}
	doc, commit, err := gitlabRender()
	if err != nil {
		return gitlabInitFail(f, "E702", err)
	}
	if f.stdout {
		_, _ = os.Stdout.Write(doc)
		return 0
	}
	root := firstOf(f.dir, os.Getenv("NSELF_CI_REPO"))
	if root == "" {
		if root, err = os.Getwd(); err != nil {
			return gitlabInitFail(f, "E702", err)
		}
	}
	if f.check {
		return gitlabCheck(context.Background(), f, root, doc)
	}
	return gitlabWrite(f, root, doc, commit)
}

func gitlabWrite(f gitlabInitFlags, root string, doc []byte, commit string) int {
	path := filepath.Join(root, gitlabtmpl.Path)
	if old, err := os.ReadFile(path); err == nil && !strings.HasPrefix(string(old), gitlabtmpl.HeaderMarker) {
		return gitlabInitFail(f, "E702", fmt.Errorf("%s exists and is not generated by this command; move it away first", gitlabtmpl.Path))
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return gitlabInitFail(f, "E702", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".nself-ci-include-")
	if err != nil {
		return gitlabInitFail(f, "E702", err)
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if _, err = tmp.Write(doc); err == nil {
		err = tmp.Chmod(0o644)
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Rename(tmp.Name(), path)
	}
	if err != nil {
		return gitlabInitFail(f, "E702", err)
	}
	if f.json {
		_ = output.WriteData(os.Stdout, "ci providers gitlab init", map[string]any{"path": gitlabtmpl.Path, "template": gitlabtmpl.Current,
			"agent_commit": commit, "untrusted_ref": pipeline.DefaultUntrustedRef}, nil)
		return 0
	}
	fmt.Printf("wrote %s (template v%d, agent commit %s)\n", gitlabtmpl.Path, gitlabtmpl.Current, commit[:12])
	fmt.Printf("next: add `include: [{local: %s}]` to .gitlab-ci.yml (forward the pipeline inputs if you use them),\n", gitlabtmpl.Path)
	fmt.Printf("      commit both to the default branch, then run: nself ci providers gitlab init --check\n")
	return 0
}

func gitlabShow(ctx context.Context, root, ref string) (string, bool) {
	out, exit, err := report.Capture(ctx, "git", "-c", "core.fsmonitor=false", "-C", root, "show", ref+":"+gitlabtmpl.Path)
	return out, err == nil && exit == 0
}

// gitlabCheck compares the include file on the default branch and on the untrusted ref, as local git
// has them, with the rendering (githubCopy is the shared per-ref result type).
func gitlabCheck(ctx context.Context, f gitlabInitFlags, root string, doc []byte) int {
	def, untrusted := defaultRemoteBranch(ctx, root), pipeline.DefaultUntrustedRef
	var copies []githubCopy
	for _, branch := range []string{def, untrusted} {
		status := "ok"
		switch got, ok := gitlabShow(ctx, root, "origin/"+branch); {
		case !ok:
			status = "missing"
		case got != string(doc):
			status = "drifted"
		}
		copies = append(copies, githubCopy{Ref: "origin/" + branch, Status: status})
	}
	var bad []string
	for _, c := range copies {
		if c.Status != "ok" {
			bad = append(bad, c.Ref)
		}
	}
	if f.json {
		_ = output.WriteData(os.Stdout, "ci providers gitlab init", map[string]any{"copies": copies, "ok": len(bad) == 0}, nil)
	} else {
		for _, c := range copies {
			fmt.Printf("%-32s %s\n", c.Ref, c.Status)
		}
		gitlabFixes(copies, def, untrusted)
	}
	if len(bad) > 0 {
		fmt.Fprintf(os.Stderr, "error: %s %s the rendering\n", strings.Join(bad, ", "), map[bool]string{true: "differ from", false: "differs from"}[len(bad) > 1])
		return 1
	}
	return 0
}

// gitlabFixes prints what the operator runs to bring the copies in line (nothing here runs them). The
// untrusted ref must stay an unprotected branch without access to protected CI/CD variables.
func gitlabFixes(copies []githubCopy, def, untrusted string) {
	if copies[0].Status != "ok" {
		fmt.Printf("\nthe default branch copy is %s: run nself ci providers gitlab init, commit %s and push it to %s\n", copies[0].Status, gitlabtmpl.Path, def)
		return
	}
	switch copies[1].Status {
	case "missing":
		fmt.Printf("\ncreate the untrusted ref from the default branch (keep it unprotected):\n  git fetch origin\n  git push origin origin/%s:refs/heads/%s\n", def, untrusted)
	case "drifted":
		fmt.Printf("\nupdate the untrusted ref to the default branch:\n  git fetch origin\n  git push --force-with-lease origin origin/%s:refs/heads/%s\n", def, untrusted)
	}
}
