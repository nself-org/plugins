package main

// Purpose: render Reference.md and splice generated regions into authored
// pages.
// Inputs:  the rows read from code (commands, codes, reasons, doctor ids),
// the exit-code table and the toolchain pins.
// Outputs: page text.
// Constraints: a region sits between <!-- BEGIN GENERATED:<name> --> and
// <!-- END GENERATED:<name> -->; a page without the markers is an error, so
// the generator never guesses where authored text ends.

import (
	"fmt"
	"sort"
	"strings"

	"github.com/nself-org/plugins/free/ci/internal/model"
	"github.com/nself-org/plugins/free/ci/internal/toolchain"
)

// refData is everything Reference.md shows.
type refData struct {
	manifest manifest
	commands []Command
	codes    []ErrorCode
	flags    []FlagRow
	reasons  []ReasonCode
	doctor   []DoctorCheck
	pins     []toolchain.Pin
}

// begin and end are the region markers of name.
func begin(name string) string { return "<!-- BEGIN GENERATED:" + name + " -->" }
func end(name string) string   { return "<!-- END GENERATED:" + name + " -->" }

// region wraps body in the markers of name.
func region(name, body string) string {
	return begin(name) + "\n" + strings.TrimRight(body, "\n") + "\n" + end(name) + "\n"
}

// splice replaces the body of region name in doc.
func splice(doc, name, body string) (string, error) {
	b, e := begin(name), end(name)
	i := strings.Index(doc, b)
	j := strings.Index(doc, e)
	if i < 0 || j < i {
		return "", fmt.Errorf("region %s: markers missing or out of order", name)
	}
	return doc[:i] + strings.TrimSuffix(region(name, body), "\n") + doc[j+len(e):], nil
}

// cell escapes text for a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", " ")
	if s == "" {
		return "-"
	}
	return s
}

// renderReference renders the whole of Reference.md.
func renderReference(d refData) string {
	var b strings.Builder
	b.WriteString("# CI reference\n\n")
	b.WriteString("<!-- Generated by `go generate ./tools/refgen/...` in free/ci. Do not edit this page by hand. -->\n\n")
	b.WriteString("Every table on this page is read from the code of `free/ci`. Change the code, then regenerate the page.\n")
	b.WriteString("For the flags of one command, run `nself ci <command> --help`.\n\n")

	var t strings.Builder
	fmt.Fprintf(&t, "## Commands\n\n`nself %s` runs the plugin binary `%s`. A v1.4 command runs without `NSELF_V15`; a v1.5 command needs `NSELF_V15=1`. Hidden commands are reachable but left out of `--help`.\n\n",
		d.manifest.Commands.Command, d.manifest.Commands.Binary)
	t.WriteString("| Command | Surface | Side effect | Summary |\n|---|---|---|---|\n")
	fmt.Fprintf(&t, "| `nself %s` | v1.4, v1.5 | %s | %s |\n", d.manifest.Commands.Command, cell(d.manifest.Commands.SideEffect), cell(d.manifest.Commands.Summary))
	for _, c := range d.commands {
		fmt.Fprintf(&t, "| `nself %s %s` | %s | %s | %s |\n", d.manifest.Commands.Command, c.Key, c.Surface, cell(c.SideEffect), cell(c.Summary))
	}
	t.WriteString("\n### Flags\n\nA flag is read from the source file that defines it. `verb *` means the flag is shared by the file that registers several sub-verbs of that verb, so it is not proven for every one of them. Run `nself ci <command> --help` for the exact set.\n\n| Flag | Commands |\n|---|---|\n")
	for _, f := range d.flags {
		var cs []string
		for _, k := range f.Commands {
			cs = append(cs, "`"+k+"`")
		}
		fmt.Fprintf(&t, "| `--%s` | %s |\n", f.Name, cell(strings.Join(cs, ", ")))
	}
	b.WriteString(region("commands", t.String()) + "\n")

	b.WriteString(region("exit-codes", "## Exit codes\n\n"+model.ExitMarkdown()) + "\n")

	t.Reset()
	t.WriteString("## Error codes\n\nErrors print as `E<number>: <message>`. The class says who fixes it: `usage` and `code` are yours, `infra` is the machine or the network.\n\n")
	t.WriteString("| Code | Class | Summary | Fix | Package |\n|---|---|---|---|---|\n")
	for _, c := range d.codes {
		fmt.Fprintf(&t, "| %s | %s | %s | %s | `%s` |\n", c.ID, cell(c.Class), cell(c.Summary), cell(c.Fix), c.Package)
	}
	b.WriteString(region("error-codes", t.String()) + "\n")

	t.Reset()
	t.WriteString("## Reason codes\n\nA reason code says why a job was skipped, held or placed where it was. `nself ci explain <job>` prints the reasons of one job.\n\n")
	t.WriteString("### Job reasons (`model.Reason`)\n\n")
	for _, r := range model.EnumValues("Reason") {
		fmt.Fprintf(&t, "- `%s`\n", r)
	}
	t.WriteString("\n### Typed reasons\n\n| Reason | Type | Package |\n|---|---|---|\n")
	for _, r := range d.reasons {
		fmt.Fprintf(&t, "| `%s` | `%s` | `%s` |\n", r.Value, r.Type, r.Package)
	}
	b.WriteString(region("reason-codes", t.String()) + "\n")

	t.Reset()
	t.WriteString("## Doctor checks\n\n`nself ci doctor` reports each check under its id. `--nodes` and `--providers` add their sections.\n\n")
	t.WriteString("| Id | Name | Package |\n|---|---|---|\n")
	for _, c := range d.doctor {
		fmt.Fprintf(&t, "| %s | %s | `%s` |\n", c.ID, cell(c.Name), c.Package)
	}
	b.WriteString(region("doctor-ids", t.String()) + "\n")

	t.Reset()
	t.WriteString("## Pinned versions\n\n")
	fmt.Fprintf(&t, "| Pin | Value |\n|---|---|\n| plugin version | %s |\n", cell(d.manifest.Version))
	for _, k := range sortedKeys(d.manifest.Requires) {
		fmt.Fprintf(&t, "| requires %s | `%s` |\n", k, d.manifest.Requires[k])
	}
	t.WriteString("\nThe toolchain pins, from `free/ci/toolchain/versions.yaml`:\n\n| Name | Kind | Version | Owner |\n|---|---|---|---|\n")
	for _, p := range d.pins {
		fmt.Fprintf(&t, "| %s | %s | `%s` | `%s` |\n", p.Name, p.Kind, cell(p.Version), p.Owner)
	}
	b.WriteString(region("pinned-versions", t.String()))
	return b.String()
}

// sortedKeys returns the keys of m in order.
func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
