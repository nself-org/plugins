package gitlabtmpl

// Purpose: render the include template (Epic D11) from the embedded template and data.
// Inputs:  Options (the pinned agent commit; Version 0 is Current).
// Outputs: the include file bytes, deterministic for the same Options; the template version.
// Constraints: output depends on nothing but Options and the embedded files (golden-tested); the
//          include file reads its values from the NSELF_CI_* environment only (pipeline variables, or
//          the main file's variables when it maps pipeline inputs), so it has no spec: header; the
//          template is read with {{ }} delimiters so GitLab's $[[ inputs.x ]] and $VAR stay literal;
//          an agent commit is 40 or 64 hex; HeaderMarker, VersionOf and AgentCommitOf are what the
//          pipeline provider and the drift check read back from a rendered file.

import (
	"bytes"
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"text/template"
)

// Current is the template version this build renders; Minimum is the oldest version the evidence
// check still accepts (v1 is the first, so N-1 is empty).
const (
	Current = 1
	Minimum = 1
)

// HeaderMarker is the first line of every rendered include file.
const HeaderMarker = "# GENERATED BY nself ci providers gitlab init — DO NOT HAND EDIT"

// Path is where the include file lives in a project.
const Path = ".gitlab/nself-ci.gitlab-ci.yml"

// Job is the name of the one job the include file defines.
const Job = "nself-ci"

// The variable (or input) names of a dispatch. The names are the same in both transports.
const (
	VarSpec      = "NSELF_CI_SPEC"
	VarDigest    = "NSELF_CI_SPEC_DIGEST"
	VarRevision  = "NSELF_CI_REVISION"
	VarAttempt   = "NSELF_CI_ATTEMPT"
	VarNonce     = "NSELF_CI_NONCE"
	VarCompat    = "NSELF_CI_COMPAT"
	VarFetchRef  = "NSELF_CI_FETCH_REF"
	VarRunnerTag = "NSELF_CI_RUNNER_TAG"
	VarTimeout   = "NSELF_CI_TIMEOUT_MINUTES"
)

// Pipeline inputs (GitLab 17.10 and later) are optional: a string inside an input must be less than 1 KB, so
// the spec travels as SpecChunks inputs of at most ChunkChars characters each; GitLab refuses inputs the
// main .gitlab-ci.yml does not declare and a pipeline takes at most 20, so the main file declares exactly
// the Inputs below (SpecChunks + 8 = 18) and maps each to the variable of the same row.
const (
	SpecChunks = 10
	ChunkChars = 1000
)

// Input is one pipeline input and the variable the main file maps it to.
type Input struct{ Name, Var string }

// Inputs lists every input the main .gitlab-ci.yml declares for the inputs transport, in order.
func Inputs() []Input {
	in := []Input{{"spec_digest", VarDigest}, {"revision", VarRevision}, {"fetch_ref", VarFetchRef}, {"attempt", VarAttempt}, {"nonce", VarNonce},
		{"compat", VarCompat}, {"runner_tag", VarRunnerTag}, {"timeout_minutes", VarTimeout}}
	for i := 0; i < SpecChunks; i++ {
		in = append(in, Input{"spec_" + strconv.Itoa(i), VarSpec + "_" + strconv.Itoa(i)})
	}
	return in
}

// RootSnippet is the YAML the project's main .gitlab-ci.yml needs to take pipeline inputs: the
// declaration, the mapping to variables and the include. The dispatch uses inputs only when the main
// file at the pipeline ref already declares all of them; otherwise it sends variables.
func RootSnippet() string {
	var b bytes.Buffer
	b.WriteString("spec:\n  inputs:\n")
	for _, in := range Inputs() {
		b.WriteString("    " + in.Name + ":\n      default: ''\n")
	}
	b.WriteString("---\nvariables:\n")
	for _, in := range Inputs() {
		b.WriteString("  " + in.Var + ": '$[[ inputs." + in.Name + " ]]'\n")
	}
	b.WriteString("include:\n  - local: " + Path + "\n")
	return b.String()
}

// RootPath is the main CI file of a project; RootKinds name the two generated variants of it.
const RootPath = ".gitlab-ci.yml"

// The generated roots of the untrusted ref.
const (
	RootVariables = "variables"
	RootInputs    = "inputs"
)

// RenderRoot returns the main .gitlab-ci.yml the untrusted ref carries: it includes the generated file
// and nothing else. The inputs variant also declares the pipeline inputs and maps them to variables.
// The untrusted ref holds exactly this file and the include file, so the coordinator can compare both
// byte for byte at the commit a pipeline ran on (anyone who can push to that ref can otherwise map the
// values to anything).
func RenderRoot(kind string) []byte {
	var b bytes.Buffer
	b.WriteString(HeaderMarker + "\n# root: " + kind + "\n")
	if kind == RootInputs {
		b.WriteString(RootSnippet())
	} else {
		b.WriteString("include:\n  - local: " + Path + "\n")
	}
	return b.Bytes()
}

// RootKindOf says which generated root file is (RootInputs, RootVariables), or "" for any other bytes.
func RootKindOf(file []byte) string {
	for _, k := range []string{RootInputs, RootVariables} {
		if bytes.Equal(file, RenderRoot(k)) {
			return k
		}
	}
	return ""
}

// CompatModes is the set of compat values; Timeouts the timeout choices the coordinator rounds up to.
var (
	CompatModes = []string{"v1.4", "v1.5"}
	Timeouts    = []int{10, 30, 60, 120, 360}
)

// Options choose the agent the job builds.
type Options struct {
	Version     int    // 0 means Current
	AgentCommit string // the pinned commit of nself-org/plugins
}

var (
	headerRE = regexp.MustCompile(`(?m)^# template: v([0-9]+)$`)
	commitAt = regexp.MustCompile(`(?m)^# agent-commit: ([0-9a-f]+)$`)
)

// Render returns the include file for o.
func Render(o Options) ([]byte, error) {
	if o.Version == 0 {
		o.Version = Current
	}
	if o.Version != Current {
		return nil, fmt.Errorf("template v%d is not available in this build", o.Version)
	}
	if !commitRE.MatchString(o.AgentCommit) {
		return nil, fmt.Errorf("the agent needs the full commit id of nself-org/plugins")
	}
	image, err := Image()
	if err != nil {
		return nil, err
	}
	raw, err := files.ReadFile("nself-ci.gitlab-ci.yml.tmpl")
	if err != nil {
		return nil, err
	}
	t, err := template.New("include").Delims("{{", "}}").Option("missingkey=error").Parse(string(raw))
	if err != nil {
		return nil, err
	}
	var snippet bytes.Buffer
	for _, ln := range strings.Split(strings.TrimRight(RootSnippet(), "\n"), "\n") {
		snippet.WriteString("#   " + ln + "\n")
	}
	var buf bytes.Buffer
	err = t.Execute(&buf, map[string]any{"Version": o.Version, "AgentCommit": o.AgentCommit, "Image": image, "Snippet": strings.TrimRight(snippet.String(), "\n")})
	if err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// VersionOf reads the template version a rendered file declares (-1 when it declares none).
func VersionOf(file []byte) int {
	m := headerRE.FindSubmatch(file[:min(len(file), 2048)])
	if m == nil {
		return -1
	}
	n, err := strconv.Atoi(string(m[1]))
	if err != nil {
		return -1
	}
	return n
}

// AgentCommitOf reads the pinned agent commit of a rendered file ("" when it names none).
func AgentCommitOf(file []byte) string {
	m := commitAt.FindSubmatch(file[:min(len(file), 2048)])
	if m == nil {
		return ""
	}
	return string(m[1])
}
