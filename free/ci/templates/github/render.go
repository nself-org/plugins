package githubtmpl

// Purpose: render the dispatch workflow (Epic D5) from the embedded template and data.
// Inputs:  Options (agent source, the pinned agent commit or the signed release pins).
// Outputs: the workflow bytes, deterministic for the same Options; the template version.
// Constraints: output depends on nothing but Options and the embedded files (golden-tested);
//          the template is read with [[ ]] delimiters so GitHub's ${{ }} stays literal; the
//          timeout options are the fixed set the coordinator rounds up to; an agent commit is
//          40 or 64 hex and release pins carry a https URL and a sha256; HeaderMarker and
//          VersionOf are what hostedev and the drift checks read back from a rendered file.

import (
	"bytes"
	"fmt"
	"net/url"
	"regexp"
	"strconv"
	"text/template"
)

// Current is the template version this build renders; Minimum is the oldest version the
// evidence check still accepts (current and N-1 are kept; v1 is the first, so N-1 is empty).
const (
	Current = 1
	Minimum = 1
)

// HeaderMarker is the first line of every rendered workflow.
const HeaderMarker = "# GENERATED BY nself ci providers github init — DO NOT HAND EDIT"

// Path is where the workflow lives in a repository.
const Path = ".github/workflows/nself-ci-dispatch.yml"

// The two ways the agent reaches the runner.
const (
	SourceMode  = "source"
	ReleaseMode = "release"
)

// Timeouts are the timeout_minutes choices; CompatModes the compat_mode choices.
var (
	Timeouts    = []int{10, 30, 60, 120, 360}
	CompatModes = []string{"v1.4", "v1.5"}
)

// ReleasePin is the verified release file of one runner platform.
type ReleasePin struct {
	RunnerOS, RunnerArch string // as GitHub names them: Linux, macOS; X64, ARM64
	URL, SHA256          string
}

// Options choose how the agent reaches the runner.
type Options struct {
	Version        int // 0 means Current
	AgentSource    string
	AgentCommit    string       // source: the pinned commit of nself-org/plugins
	ReleaseVersion string       // release: the pinned agent version
	Pins           []ReleasePin // release: one per supported runner platform
}

var (
	commitRE  = regexp.MustCompile(`^([0-9a-f]{40}|[0-9a-f]{64})$`)
	sumRE     = regexp.MustCompile(`^[0-9a-f]{64}$`)
	versionRE = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$`)
	osRE      = regexp.MustCompile(`^(Linux|macOS)$`)
	archRE    = regexp.MustCompile(`^(X64|ARM64)$`)
	headerRE  = regexp.MustCompile(`(?m)^# template: v([0-9]+)$`)
)

func (o Options) check() error {
	switch o.AgentSource {
	case SourceMode:
		if !commitRE.MatchString(o.AgentCommit) {
			return fmt.Errorf("agent source needs the full commit id of nself-org/plugins")
		}
	case ReleaseMode:
		if !versionRE.MatchString(o.ReleaseVersion) || len(o.Pins) == 0 {
			return fmt.Errorf("agent release needs a version and at least one verified pin")
		}
		for _, p := range o.Pins {
			u, err := url.Parse(p.URL)
			if err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil || !sumRE.MatchString(p.SHA256) ||
				!osRE.MatchString(p.RunnerOS) || !archRE.MatchString(p.RunnerArch) || hasQuote(p.URL) {
				return fmt.Errorf("agent release pin for %s %s is not valid", p.RunnerOS, p.RunnerArch)
			}
		}
	default:
		return fmt.Errorf("agent source must be release or source, not %q", o.AgentSource)
	}
	return nil
}

func hasQuote(s string) bool {
	for _, c := range s {
		if c == '\'' || c == '\n' || c == '\r' || c == ' ' {
			return true
		}
	}
	return false
}

// Render returns the workflow for o.
func Render(o Options) ([]byte, error) {
	if o.Version == 0 {
		o.Version = Current
	}
	if o.Version != Current {
		return nil, fmt.Errorf("template v%d is not available in this build", o.Version)
	}
	if err := o.check(); err != nil {
		return nil, err
	}
	labels, err := LabelNames()
	if err != nil {
		return nil, err
	}
	pins, err := Actions()
	if err != nil {
		return nil, err
	}
	raw, err := files.ReadFile("nself-ci-dispatch.yml.tmpl")
	if err != nil {
		return nil, err
	}
	t, err := template.New("dispatch").Delims("[[", "]]").Option("missingkey=error").Parse(string(raw))
	if err != nil {
		return nil, err
	}
	timeouts := make([]string, len(Timeouts))
	for i, m := range Timeouts {
		timeouts[i] = strconv.Itoa(m)
	}
	var buf bytes.Buffer
	err = t.Execute(&buf, map[string]any{
		"Version": o.Version, "AgentSource": o.AgentSource, "AgentCommit": o.AgentCommit, "ReleaseVersion": o.ReleaseVersion,
		"Pins": o.Pins, "Labels": labels, "CompatModes": CompatModes, "Timeouts": timeouts,
		"Checkout": pins["checkout"], "SetupGo": pins["setup-go"], "Upload": pins["upload-artifact"],
	})
	if err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// VersionOf reads the template version a rendered workflow declares (-1 when it declares none).
func VersionOf(workflow []byte) int {
	m := headerRE.FindSubmatch(workflow[:min(len(workflow), 2048)])
	if m == nil {
		return -1
	}
	n, err := strconv.Atoi(string(m[1]))
	if err != nil {
		return -1
	}
	return n
}

// AgentCommitOf reads the pinned agent commit of a source-mode workflow ("" for release mode).
func AgentCommitOf(workflow []byte) string {
	m := regexp.MustCompile(`(?m)^# agent-commit: ([0-9a-f]+)$`).FindSubmatch(workflow[:min(len(workflow), 2048)])
	if m == nil {
		return ""
	}
	return string(m[1])
}
