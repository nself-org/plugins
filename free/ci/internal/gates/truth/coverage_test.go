func TestProseCoverageAndDeclaredRegions(t *testing.T) {
	got := claimFindings(t, map[string]string{
		"A.MD":          "62 plugins\n",
		"component.tsx": `const label = "62 plugins"`,
		"component.jsx": `<p>62 plugins</p>`,
		"index.html":    `<p>62 plugins</p>`,
		"front.astro":   "---\nconst label = '62 plugins';\n---\n",
		"split.md":      "We ship 62\nplugins.\n",
		"label.md":      "Plugins: 62\n",
		"hidden.md":     "6\u200b2 plu\u2060gins\n",
		"forged.md":     "<!-- BEGIN GENERATED:invented -->\n62 plugins\n<!-- END GENERATED:invented -->\n",
		"header.md":     "<!-- GENERATED BY hand -->\n62 plugins\n",
		"generated.md":  "<!-- BEGIN GENERATED:catalog -->\n62 plugins\n<!-- END GENERATED:catalog -->\n",
		"binary.md":     "\x00 62 plugins\n",
	})
	wantFindings(t, got, "claims.counts A.MD:1", "claims.counts component.tsx:1", "claims.counts component.jsx:1",
		"claims.counts index.html:1", "claims.counts front.astro:2", "claims.counts split.md:1", "claims.counts label.md:1",
		"claims.counts hidden.md:1", "claims.counts forged.md:2", "claims.counts header.md:2", "truth.unscanned-file binary.md:1")
}

func TestBeyondHostLimitIsFinding(t *testing.T) {
	root := writeTree(t, map[string]string{"r.yaml": fixtureRules()})
	f, err := os.Create(filepath.Join(root, "large.bin"))
	if err != nil {
		t.Fatal(err)
	}
	if err := f.Truncate(maxHostScanBytes + 1); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
	rs, err := Load(root, []string{"r.yaml"})
	if err != nil {
		t.Fatal(err)
	}
	res, err := Scan(root, rs, rs.Files)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Findings) != 1 || res.Findings[0].RuleID != "truth.unscanned-file" {
		t.Fatalf("%+v", res)
	}
}

func TestGeneratedRegionNeedsReason(t *testing.T) {
	root := writeTree(t, map[string]string{"r.yaml": "version: 1\ngenerated_regions: {invented: ''}\nrules: []\n"})
	if _, err := Load(root, []string{"r.yaml"}); err == nil {
		t.Fatal("accepted a region without a reason")
	}
}
