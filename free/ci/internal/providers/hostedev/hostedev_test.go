func zipOf(t *testing.T, files map[string][]byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for name, body := range files {
		w, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err = w.Write(body); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func evidenceZip(t *testing.T, mut func(*model.Evidence)) []byte {
	t.Helper()
	ev := sampleEvidence()
	if mut != nil {
		mut(&ev)
	}
	b, err := json.Marshal(ev)
	if err != nil {
		t.Fatal(err)
	}
	return zipOf(t, map[string][]byte{hostedev.EvidenceFile: b})
}

func good(t *testing.T) hostedev.VerifyInput {
	t.Helper()
	spec := []byte(`{"kind":"test","run":["true"]}`)
	sum := sha256.Sum256(spec)
	return hostedev.VerifyInput{
		Provider: "github-hosted",
		Run: hostedev.Run{ID: "9001", Event: "workflow_dispatch", Path: wfPath, HeadBranch: "main", HeadSHA: strings.Repeat("a", 40),
			DisplayTitle: "nself-ci " + nonce, RunAttempt: 1},
		Want:          hostedev.Want{Event: "workflow_dispatch", Path: wfPath, Ref: "main"},
		WorkflowBytes: []byte(wfSource),
		Rendering: func(v int) ([]byte, error) {
			if v == 2 {
				return []byte(wfSource), nil
			}
			return nil, providers.NewError(providers.Config, "E705", "no such rendering", 0, time.Time{})
		},
		MinTemplate: 2, Nonce: nonce, AttemptID: attempt, AttemptN: 2, Revision: rev,
		SpecDigest: "sha256:" + hex.EncodeToString(sum[:]), Spec: spec, MinAgent: "1",
		ArtifactID: "314", ArtifactSize: 900, EvidenceZip: evidenceZip(t, nil), Now: time.Date(2026, 10, 19, 12, 0, 0, 0, time.UTC),
	}
}

func verifyErr(in hostedev.VerifyInput) error {
	_, err := hostedev.Verify(context.Background(), in)
	return err
}

func reasonOf(t *testing.T, err error) string {
	t.Helper()
	var pe *providers.Error
	if !errors.As(err, &pe) || pe.Code != "E705" {
		t.Fatalf("not an E705: %v", err)
	}
	return pe.Reason
}

// TestEvidenceRejections proves each acceptance rejection has its own E705 reason key: a run whose
// event is not workflow_dispatch, another workflow path, another dispatch ref, a missing nonce, an
// edited workflow (one byte), a stale template, a stale producer, a spec digest, revision or attempt
// mismatch, a missing artifact and a 17 MiB artifact.
func TestEvidenceRejections(t *testing.T) {
	cases := []struct {
		name, reason string
		mut          func(*hostedev.VerifyInput)
	}{
		{"event", hostedev.ReasonEvent, func(in *hostedev.VerifyInput) { in.Run.Event = "push" }},
		{"path", hostedev.ReasonPath, func(in *hostedev.VerifyInput) { in.Run.Path = ".github/workflows/other.yml" }},
		{"ref", hostedev.ReasonRef, func(in *hostedev.VerifyInput) { in.Run.HeadBranch = "attacker" }},
		{"rerun", hostedev.ReasonRerun, func(in *hostedev.VerifyInput) { in.Run.RunAttempt = 2 }},
		{"nonce", hostedev.ReasonNonce, func(in *hostedev.VerifyInput) { in.Run.DisplayTitle = "nself-ci something-else" }},
		{"edited by one byte", hostedev.ReasonEdited, func(in *hostedev.VerifyInput) { in.WorkflowBytes = append(append([]byte{}, in.WorkflowBytes...), ' ') }},
		{"no template header", hostedev.ReasonTemplate, func(in *hostedev.VerifyInput) { in.WorkflowBytes = []byte("name: bare\n") }},
		{"stale template", hostedev.ReasonStale, func(in *hostedev.VerifyInput) { in.MinTemplate = 3 }},
		{"producer below minimum", hostedev.ReasonProducerStale, func(in *hostedev.VerifyInput) { in.MinAgent = "1.5.0" }},
		{"spec digest", hostedev.ReasonSpec, func(in *hostedev.VerifyInput) { in.Spec = []byte(`{"kind":"test","run":["false"]}`) }},
		{"spec digest malformed", hostedev.ReasonSpec, func(in *hostedev.VerifyInput) { in.SpecDigest, in.Spec = "sha256:short", nil }},
		{"revision", hostedev.ReasonRevision, func(in *hostedev.VerifyInput) { in.Revision = strings.Repeat("9", 40) }},
		{"attempt", hostedev.ReasonAttempt, func(in *hostedev.VerifyInput) { in.AttemptID = "attempt-8" }},
		{"missing artifact", hostedev.ReasonMissing, func(in *hostedev.VerifyInput) { in.EvidenceZip, in.ArtifactSize = nil, 0 }},
		{"17 MiB artifact", hostedev.ReasonTooLarge, func(in *hostedev.VerifyInput) { in.ArtifactSize = 17 << 20 }},
		{"17 MiB download", hostedev.ReasonTooLarge, func(in *hostedev.VerifyInput) { in.EvidenceZip, in.ArtifactSize = make([]byte, 17<<20), 0 }},
		{"not a zip", hostedev.ReasonArtifact, func(in *hostedev.VerifyInput) { in.EvidenceZip = []byte("PK nope") }},
		{"two files", hostedev.ReasonArtifact, func(in *hostedev.VerifyInput) {
			in.EvidenceZip = zipOf(t, map[string][]byte{"evidence.json": []byte("{}"), "extra": []byte("x")})
		}},
		{"wrong file name", hostedev.ReasonArtifact, func(in *hostedev.VerifyInput) {
			in.EvidenceZip = zipOf(t, map[string][]byte{"../evidence.json": []byte("{}")})
		}},
		{"not evidence", hostedev.ReasonEvidence, func(in *hostedev.VerifyInput) {
			in.EvidenceZip = zipOf(t, map[string][]byte{"evidence.json": []byte(`{"attempt":"a"}`)})
		}},
		{"schema string", hostedev.ReasonEvidence, func(in *hostedev.VerifyInput) {
			in.EvidenceZip = evidenceZip(t, func(e *model.Evidence) { e.Schema = "ci.evidence/v9" })
		}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			in := good(t)
			c.mut(&in)
			if got := reasonOf(t, verifyErr(in)); got != c.reason {
				t.Fatalf("reason = %q, want %q", got, c.reason)
			}
		})
	}
}

// TestAcceptedEvidence proves good evidence is accepted and the attestation has every field set.
func TestAcceptedEvidence(t *testing.T) {
	in := good(t)
	att, err := hostedev.Verify(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	v := reflect.ValueOf(att)
	for i := 0; i < v.NumField(); i++ {
		if v.Field(i).IsZero() {
			t.Errorf("attestation field %s is empty", v.Type().Field(i).Name)
		}
	}
	if att.RunID != "9001" || att.Nonce != nonce || att.WorkflowSHA != strings.Repeat("a", 40) || att.TemplateVersion != "v2" ||
		att.RunAttempt != 2 || att.Ref != rev || att.ArtifactID != "314" || att.WorkflowPath != wfPath {
		t.Fatalf("attestation: %+v", att)
	}
	zs := sha256.Sum256(in.EvidenceZip)
	if att.ArtifactSHA256 != "sha256:"+hex.EncodeToString(zs[:]) || att.VerifiedAt != "2026-10-19T12:00:00Z" {
		t.Fatalf("attestation digests: %+v", att)
	}
	// An uppercase revision and a newer producer version are accepted.
	in = good(t)
	in.Revision = strings.ToUpper(rev)
	in.EvidenceZip = evidenceZip(t, func(e *model.Evidence) { e.Producer.Version = "1.5.2" })
	in.MinAgent = "1.5"
	if _, err = hostedev.Verify(context.Background(), in); err != nil {
		t.Fatal(err)
	}
}

// TestErrorTextIsTheKeyOnly proves a rejection never echoes the document.
func TestErrorTextIsTheKeyOnly(t *testing.T) {
	in := good(t)
	in.EvidenceZip = zipOf(t, map[string][]byte{"evidence.json": []byte(`{"note":"hunter2-value"}`)})
	if err := verifyErr(in); err == nil || strings.Contains(err.Error(), "hunter2") {
		t.Fatalf("error: %v", err)
	}
}
