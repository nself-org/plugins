package darwin

// Purpose: the sudoers drop-in of a macOS system node and the scripts that install and check it
// (Epic D20): one rule per slot user that lets `nself-ci` run the job shim, and only the job shim, as
// that user. The file is generated here, copied to the node, validated there with `visudo -cf`, and
// installed with `install -m 0440 -o root -g wheel` (no heredoc, no shell-built file content).
// Inputs:  the slot count.
// Outputs: the drop-in text and two scripts.
// Constraints: the stage file name is fixed; /etc/sudoers is touched only to add the includedir line when
//          the stock file lacks it, and is restored on any failure; a failed validation leaves the old
//          drop-in (or none) in place; the rule grants nothing beyond the shim (no ALL, no admin group).

import (
	"fmt"
	"strings"
)

// SudoersStage is the file name, in the ssh user's home, the drop-in is copied to before it is installed.
const SudoersStage = ".nself-ci-sudoers.stage"

// Sudoers is the drop-in text: one rule per slot user.
func Sudoers(slots int) string {
	var b strings.Builder
	b.WriteString("# nSelf CI agent: the agent user may start the job shim as each job user, and nothing else.\n")
	b.WriteString("# GENERATED BY nself ci nodes add --system; DO NOT HAND EDIT.\n")
	for n := 1; n <= slots; n++ {
		fmt.Fprintf(&b, "%s ALL=(%s) NOPASSWD: %s job-shim\n", agentUser, jobUser(n), agentPath)
	}
	return b.String()
}

// sudoersScript validates the staged drop-in and installs it. The whole sudoers set is checked after
// the install; on failure the previous drop-in comes back and /etc/sudoers is restored.
func sudoersScript() string {
	return fmt.Sprintf(scriptHead+`umask 077
tmp=$(mktemp -d "${TMPDIR:-/tmp}/nself-ci.XXXXXX")
cp /etc/sudoers "$tmp/sudoers.orig"
had=0
if [ -e %[1]s ]; then had=1; cp %[1]s "$tmp/dropin.orig"; fi
ok=0
cleanup() {
  if [ "$ok" != 1 ]; then
    if [ "$had" = 1 ]; then cp "$tmp/dropin.orig" %[1]s 2>/dev/null || true; else rm -f %[1]s; fi
    if ! cmp -s "$tmp/sudoers.orig" /etc/sudoers; then cp "$tmp/sudoers.orig" /etc/sudoers 2>/dev/null || true; fi
  fi
  rm -rf "$tmp"
  rm -f ./%[2]s
}
trap cleanup EXIT
visudo -cf ./%[2]s >/dev/null
grep -Eq '^[#@]includedir[[:space:]]+(/private)?%[3]s([[:space:]]|$)' /etc/sudoers || { echo >> /etc/sudoers; echo '#includedir %[3]s' >> /etc/sudoers; }
mkdir -p %[3]s
install -o root -g wheel -m 0440 ./%[2]s %[1]s
rm -f ./%[2]s
visudo -c >/dev/null 2>&1 || { echo 'sudoers did not validate; the previous set is back in place' >&2; exit 1; }
ok=1
`, SudoersPath, SudoersStage, sudoersDir)
}

// verifyScript checks the layout after an install: every account exists, is hidden, has shell
// /usr/bin/false and an id in range, is in no admin group, the state directory is the agent's alone,
// and sudo itself lists exactly one job-shim rule per slot for the agent user and nothing else. Every
// uid and gid is unique on the machine, each user's group id is its group's, and the root-owned copy of the
// agent (the only binary uninstall may run as root) is root's alone.
func verifyScript(slots int) string {
	return fmt.Sprintf(scriptHead+`[ "$(stat -f '%%Lp %%Su' %[2]s)" = "700 %[1]s" ]
[ "$(stat -f '%%Lp %%Su' %[10]s)" = "755 root" ]
[ "$(stat -f '%%Lp %%Su' %[10]s/bin)" = "755 %[1]s" ]
[ "$(stat -f '%%Lp %%Su' %[11]s)" = "755 root" ]
for u in %[1]s $(for n in %[3]s; do echo %[1]s-job-$n; done); do
  dscl . -read "/Users/$u" UniqueID >/dev/null
  [ "$(dscl . -read "/Users/$u" IsHidden | awk '{print $NF}')" = 1 ]
  [ "$(dscl . -read "/Users/$u" UserShell | awk '{print $NF}')" = /usr/bin/false ]
  uid=$(dscl . -read "/Users/$u" UniqueID | awk '{print $NF}')
  { [ "$uid" -ge %[6]d ] && [ "$uid" -le %[7]d ]; } || { echo "$u has uid $uid, outside %[6]d-%[7]d" >&2; exit 1; }
  [ "$(dscl . -list /Users UniqueID | awk -v id="$uid" '$2 == id' | wc -l | tr -d ' ')" = 1 ] || { echo "uid $uid is shared" >&2; exit 1; }
  gid=$(dscl . -read "/Users/$u" PrimaryGroupID | awk '{print $NF}')
  [ "$(dscl . -read "/Groups/$u" PrimaryGroupID | awk '{print $NF}')" = "$gid" ] || { echo "$u: group id differs from the user's" >&2; exit 1; }
  [ "$(dscl . -list /Groups PrimaryGroupID | awk -v id="$gid" '$2 == id' | wc -l | tr -d ' ')" = 1 ] || { echo "gid $gid is shared" >&2; exit 1; }
  if id -Gn "$u" | grep -qwE 'admin|wheel|_appserveradm|_appserverusr'; then echo "$u is in a privileged group" >&2; exit 1; fi
done
for n in %[3]s; do [ -d %[8]s/$n ]; done
[ ! -e %[9]s ] || [ "$(stat -f '%%Lp %%Su' %[9]s)" = "755 root" ]
rules=$(sudo -n -l -U %[1]s 2>/dev/null | grep -c '%[4]s job-shim' || true)
[ "$rules" = %[5]d ] || { echo "sudo lists $rules job-shim rules, want %[5]d" >&2; exit 1; }
all=$(sudo -n -l -U %[1]s 2>/dev/null | grep -cE '^[[:space:]]*[(]' || true)
[ "$all" = %[5]d ] || { echo "sudo lists $all rules for %[1]s, want only the %[5]d job-shim rules" >&2; exit 1; }
`, agentUser, StateDir, slotList(slots), agentPath, slots, IDLow, IDHigh, JobsDir, TrustedPath, agentDir, logDir)
}
