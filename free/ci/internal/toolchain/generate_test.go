package toolchain

// Purpose: the generator and drift test of versions.yaml. With -write it
// rewrites toolchain/versions.yaml and the embedded copy (go generate runs
// it so); without, it fails when either file differs from what the pins render.

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"strings"
	"testing"
)

var write = flag.Bool("write", false, "rewrite toolchain/versions.yaml and the embedded copy")

const (
	toolchainDir = "../../toolchain"
	canonical    = toolchainDir + "/versions.yaml"
	embeddedCopy = "versions.yaml"
)

func loadPinsFromRepo(t *testing.T) []Pin {
	t.Helper()
	pins, err := LoadPins(os.DirFS(toolchainDir), "pins")
	if err != nil {
		t.Fatal(err)
	}
	return pins
}

func TestVersionsDrift(t *testing.T) {
	want, err := Render(loadPinsFromRepo(t))
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{canonical, embeddedCopy} {
		if *write {
			if err := os.WriteFile(path, want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		have, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(have, want) {
			t.Errorf("%s differs from the pins: run `go generate ./internal/toolchain/...` in free/ci", path)
		}
	}
}

func TestVersionsGeneratedMarker(t *testing.T) {
	for _, path := range []string{canonical, embeddedCopy} {
		b, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		head := string(b)
		if len(head) > 300 {
			head = head[:300]
		}
		if !strings.Contains(head, "GENERATED BY") || !strings.Contains(head, "DO NOT HAND EDIT") {
			t.Errorf("%s lacks the GENERATED BY / DO NOT HAND EDIT marker", path)
		}
		// generated-file-gate.yml fails a tracked file with this exact string in its first 5 lines.
		if strings.Contains(strings.Join(strings.SplitN(head, "\n", 6)[:5], "\n"), "# GENERATED BY") {
			t.Errorf("%s would trip the generated-file gate", path)
		}
	}
}

// TestEveryRowHasSHA256: each tool source carries a sha256, each base image a
// digest, the image row is pending or digest-pinned (acceptance).
func TestEveryRowHasSHA256(t *testing.T) {
	v, err := Embedded()
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range v.Rows {
		switch r.Kind {
		case KindTool:
			for _, s := range r.Sources {
				if !sha256Re.MatchString(s.SHA256) {
					t.Errorf("%s %s/%s has no sha256", r.Name, s.OS, s.Arch)
				}
			}
		case KindBaseImage:
			if !digestRe.MatchString(r.Digest) {
				t.Errorf("%s has no digest", r.Name)
			}
		case KindImage:
			if r.Status == StatusPending && r.Digest != "" {
				t.Errorf("%s is pending with a digest", r.Name)
			}
		}
	}
}

// TestSyftRow: the CACHE delta 4 row, one source per os/arch pair.
func TestSyftRow(t *testing.T) {
	v, err := Embedded()
	if err != nil {
		t.Fatal(err)
	}
	row, ok := v.Row("syft")
	if !ok {
		t.Fatal("no syft row")
	}
	got := map[string]bool{}
	for _, s := range row.Sources {
		got[s.OS+"/"+s.Arch] = sha256Re.MatchString(s.SHA256)
	}
	for _, want := range []string{"linux/amd64", "linux/arm64", "darwin/amd64", "darwin/arm64"} {
		if !got[want] {
			t.Errorf("syft has no checksummed source for %s", want)
		}
	}
	if row.Version == "" || row.Owner != "internal/sbom" {
		t.Errorf("syft row %+v", row)
	}
}

// TestEmbeddedImageRowIsPinned: the owner-named first publish (P7-CI-61) pinned the row to the pushed manifest list.
func TestEmbeddedImageRowIsPinned(t *testing.T) {
	v, err := Embedded()
	if err != nil {
		t.Fatal(err)
	}
	row, ok := v.Row(ImageRow)
	if !ok || row.Status != StatusPinned || row.Image != "docker.io/nself/ci-toolchain" || !digestRe.MatchString(row.Digest) || row.Version != row.Image+"@"+row.Digest {
		t.Fatalf("image row %+v", row)
	}
}

// TestImageRowMatchesTheImageLock: the pinned row and images.d/ci-toolchain.json name the same reference, so the daily
// probe watches the image `nself ci --container` pulls (P7-CI-61).
func TestImageRowMatchesTheImageLock(t *testing.T) {
	v, err := Embedded()
	if err != nil {
		t.Fatal(err)
	}
	row, _ := v.Row(ImageRow)
	raw, err := os.ReadFile("../../../../images.d/ci-toolchain.json")
	if err != nil {
		t.Fatal(err)
	}
	var frag struct {
		Name, Kind, Image string
	}
	if err := json.Unmarshal(raw, &frag); err != nil {
		t.Fatal(err)
	}
	if frag.Name != "ci-toolchain" || frag.Kind != "ci" || frag.Image != row.Image+"@"+row.Digest {
		t.Fatalf("lock fragment %+v does not match the pinned row %s@%s", frag, row.Image, row.Digest)
	}
}
