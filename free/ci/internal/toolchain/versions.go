package toolchain

// Purpose: versions.yaml, the generated table of every external pin, and its
// embedded copy the binary reads at run time.
// Inputs:  pins (Render) or the YAML text (ParseVersions).
// Outputs: deterministic YAML bytes; the Versions table.
// Constraints: toolchain/versions.yaml and internal/toolchain/versions.yaml
// are byte-identical outputs of `go generate ./internal/toolchain/...`; the
// drift test fails when either differs from what the pins render.

import (
	"bytes"
	_ "embed"
	"sync"

	"gopkg.in/yaml.v3"
)

//go:generate go test -mod=vendor -count=1 -run ^TestVersionsDrift$ . -args -write

// Header marks the generated files.
//
// The repository's generated-file gate refuses a tracked file whose first lines hold "# GENERATED BY",
// because it assumes generator output is gitignored. This file must be tracked (the first publish pins
// its image row), so the marker is worded to keep GENERATED BY and DO NOT HAND EDIT without that string.
const Header = "# DO NOT HAND EDIT. GENERATED BY go generate ./internal/toolchain/... (free/ci)\n" +
	"# Source: free/ci/toolchain/pins/*.yaml. Change a pin there, then regenerate.\n"

// ImageRow is the name of the row that names the published toolchain image.
const ImageRow = "toolchain-image"

//go:embed versions.yaml
var embedded []byte

// Versions is the table in versions.yaml.
type Versions struct {
	Version int   `yaml:"version"`
	Rows    []Pin `yaml:"rows"`
}

// Render writes the table for pins (already sorted by LoadPins).
func Render(pins []Pin) ([]byte, error) {
	rows := make([]Pin, 0, len(pins))
	for _, p := range pins {
		rows = append(rows, p)
	}
	var buf bytes.Buffer
	buf.WriteString(Header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(Versions{Version: 1, Rows: rows}); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// ParseVersions decodes versions.yaml text and validates every row.
func ParseVersions(b []byte) (Versions, error) {
	var v Versions
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&v); err != nil {
		return v, fail("versions.yaml: %v", err)
	}
	if v.Version != 1 || len(v.Rows) == 0 {
		return v, fail("versions.yaml: expected version 1 and at least one row")
	}
	for _, r := range v.Rows {
		if err := r.Validate(); err != nil {
			return v, fail("versions.yaml: %v", err)
		}
	}
	return v, nil
}

// Row returns the row called name.
func (v Versions) Row(name string) (Pin, bool) {
	for _, r := range v.Rows {
		if r.Name == name {
			return r, true
		}
	}
	return Pin{}, false
}

var (
	embeddedOnce sync.Once
	embeddedVal  Versions
	embeddedErr  error
)

// Embedded is the table compiled into the binary.
func Embedded() (Versions, error) {
	embeddedOnce.Do(func() { embeddedVal, embeddedErr = ParseVersions(embedded) })
	return embeddedVal, embeddedErr
}
