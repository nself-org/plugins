package config

// Purpose: render a Migration as `.nself/ci.yaml` text, show it as a diff and
// write it.
// Inputs:  a Migration and a repo root.
// Outputs: YAML bytes (jobs in stage order, comments naming each source
// stage), a unified-style diff against the current file, and the written file.
// Constraints: nothing is written without Write being called (`--write`);
// an existing `.nself/ci.yaml` with other content is never overwritten; the
// rendered text must pass Parse before it is returned.

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

type jobOut struct {
	Kind     string   `yaml:"kind"`
	Run      []string `yaml:"run,flow"`
	Workdir  string   `yaml:"workdir,omitempty"`
	Timeout  string   `yaml:"timeout,omitempty"`
	Required *bool    `yaml:"required,omitempty"`
	When     *whenOut `yaml:"when,omitempty"`
}

type whenOut struct {
	Paths      []string `yaml:"paths,omitempty,flow"`
	EnvPresent []string `yaml:"env_present,omitempty,flow"`
}

func (m *Migration) render() error {
	jobs := &yaml.Node{Kind: yaml.MappingNode}
	for _, id := range m.Order {
		j := m.Config.Jobs[id]
		out := jobOut{Kind: string(j.Kind), Run: j.Run, Workdir: j.Workdir, Timeout: j.Timeout, Required: j.Required}
		if j.When != nil {
			out.When = &whenOut{Paths: j.When.Paths, EnvPresent: j.When.EnvPresent}
		}
		val := &yaml.Node{}
		if err := val.Encode(out); err != nil {
			return err
		}
		key := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: id, HeadComment: "# " + strings.Join(m.notes[id], "\n# ")}
		jobs.Content = append(jobs.Content, key, val)
	}
	root := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{
		{Kind: yaml.ScalarNode, Tag: "!!str", Value: "version", HeadComment: "# Generated by `nself ci config migrate`; review it, then delete the legacy .ci.yaml files."},
		{Kind: yaml.ScalarNode, Tag: "!!int", Value: "1"},
		{Kind: yaml.ScalarNode, Tag: "!!str", Value: "jobs"},
		jobs,
	}}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	m.YAML = buf.Bytes()
	if _, err := Parse(FileName, m.YAML); err != nil {
		return fmt.Errorf("migrated config does not validate: %w", err)
	}
	return nil
}

// Diff shows what writing the migration would change under root.
func (m *Migration) Diff(root string) (string, error) {
	current, err := readRegular(filepath.Join(root, FileName))
	switch {
	case err == nil && bytes.Equal(current, m.YAML):
		return "", nil
	case err != nil && !os.IsNotExist(err):
		return "", &Error{Code: CodeInvalid, Problems: []Problem{{File: FileName, Message: err.Error()}}}
	}
	var b strings.Builder
	from := "a/" + FileName
	if os.IsNotExist(err) {
		from = "/dev/null"
	}
	fmt.Fprintf(&b, "--- %s\n+++ b/%s\n", from, FileName)
	for _, line := range strings.Split(strings.TrimRight(string(current), "\n"), "\n") {
		if line != "" || len(current) > 0 {
			b.WriteString("-" + line + "\n")
		}
	}
	for _, line := range strings.Split(strings.TrimRight(string(m.YAML), "\n"), "\n") {
		b.WriteString("+" + line + "\n")
	}
	return b.String(), nil
}

// Write creates root/.nself/ci.yaml. It refuses to replace a file that holds
// other content (merge by hand) and succeeds quietly when the file is identical.
func (m *Migration) Write(root string) error {
	path := filepath.Join(root, FileName)
	// Never write through a symlink: it could point outside the repo root.
	for _, p := range []string{filepath.Dir(path), path} {
		if info, err := os.Lstat(p); err == nil && info.Mode()&os.ModeSymlink != 0 {
			return &Error{Code: CodeInvalid, Problems: []Problem{{File: FileName, Message: p + " is a symlink; replace it with a real file or directory before migrating"}}}
		}
	}
	if current, err := readRegular(path); err == nil {
		if bytes.Equal(current, m.YAML) {
			return nil
		}
		return &Error{Code: CodeInvalid, Problems: []Problem{{File: FileName, Message: "already exists with other content; merge the planned jobs by hand (run without --write to see them)"}}}
	} else if !os.IsNotExist(err) {
		return &Error{Code: CodeInvalid, Problems: []Problem{{File: FileName, Message: err.Error()}}}
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	if _, err := f.Write(m.YAML); err != nil {
		_ = f.Close()
		return err
	}
	return f.Close()
}
