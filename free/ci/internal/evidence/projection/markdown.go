package projection

import (
	"fmt"
	"strings"
)

// Page renders Evidence-Projection.md from the same mapping tables Project
// reads, so the page cannot list a field the projection lacks.
func Page() string {
	var b strings.Builder
	b.WriteString("<!-- GENERATED BY internal/evidence/projection DO NOT HAND EDIT -->\n")
	b.WriteString("# Evidence projection `" + Name + "`\n\n")
	b.WriteString("`projection.Project(doc, \"" + Name + "\")` is a pure function of one `ci.evidence/v1` document. ")
	b.WriteString("It is a view, not a second schema. A source key that is absent (a document from before the additive keys) or null projects as `null` with a reason.\n\n")
	b.WriteString("| Projected field | Source key in ci.evidence/v1 |\n|---|---|\n")
	for _, m := range Mappings() {
		fmt.Fprintf(&b, "| `%s` | `%s` |\n", m.Field, m.Source)
	}
	return b.String()
}
