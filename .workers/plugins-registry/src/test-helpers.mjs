/**
 * test-helpers.mjs — shared fixtures for the worker tests (P7-PLUG-08).
 *
 * Everything is synthetic: fake KV, fake ExecutionContext, a recording fetch
 * stub. No network, no secret, no real token value anywhere. Tests import the
 * esbuild bundle of src/index.ts (dist-test/index.mjs, built by `pnpm test`).
 */

import { createHash } from 'node:crypto';

/** Map-backed KVNamespace stand-in: get(key, type), put, delete. */
export function fakeKv(seed = {}) {
  const store = new Map(Object.entries(seed).map(([k, v]) => [k, typeof v === 'string' ? v : JSON.stringify(v)]));
  return {
    store,
    async get(key, type) {
      if (!store.has(key)) return null;
      const raw = store.get(key);
      return type === 'json' || (type && type.type === 'json') ? JSON.parse(raw) : raw;
    },
    async put(key, value) {
      store.set(key, value);
    },
    async delete(key) {
      store.delete(key);
    },
  };
}

/** ExecutionContext whose waitUntil promises can be awaited with settle(). */
export function fakeCtx() {
  const pending = [];
  return {
    waitUntil: (p) => pending.push(Promise.resolve(p).catch(() => {})),
    settle: () => Promise.all(pending),
  };
}

/** A KV envelope as the worker stores it. */
export const envelope = (data, ageMs = 0) => ({ data, timestamp: Date.now() - ageMs });

/** sha256 hex of a string, computed outside the worker. */
export const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/** Base64 GitHub Contents API response body for a JSON document. */
export const contentsResponse = (doc) =>
  new Response(JSON.stringify({ content: Buffer.from(JSON.stringify(doc, null, 2)).toString('base64') }), {
    status: 200,
  });

